"""External execution contracts, independent of the internal paper broker."""
from typing import Protocol


class ExternalBroker(Protocol):
    def account(self) -> dict: ...
    def positions(self) -> list[dict]: ...
    def require_underlying(self, instrument_id: int) -> None: ...
    def prepare_order(self, *, instrument_id: int, quantity: int, stop, target) -> dict: ...
    def lookup(self, *, order_id=None, reference_id=None) -> dict: ...
    def submit(self, payload: dict, *, request_id: str, confirmed: bool) -> dict: ...
    def close_position(self, position_id: int, instrument_id: int, *, request_id: str, confirmed: bool) -> dict: ...
    def lookup_close(self, order_id: int) -> dict: ...


class QuoteProvider(Protocol):
    def quote(self, symbol: str, side: str = 'BUY'): ...


class InstrumentResolver(Protocol):
    def resolve(self, symbol: str) -> dict: ...
    def require_us_stock(self, instrument: dict) -> None: ...
